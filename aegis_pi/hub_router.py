"""AEGIS Raspberry Pi Central Hub Router.
Orchestrates the 8 DGX Spark machines via Hub-and-Spoke topology.
Enforces strict node isolation, dictates Google Drive transfer commands, and manages multi-agent handoffs.
"""
import asyncio
import httpx
from typing import Dict, Any, Optional
from datetime import datetime

from aegis_core.models import TaskRecord, TaskStep
from aegis_core.storage_manager import AEGISStorageSystem
from aegis_core.safety_guard import SafetyGuard
from aegis_core.voice.dialogue_manager import DialogueManager

class PiHubRouter:
    def __init__(self, nodes_config_path: str = "config/nodes.json"):
        self.storage = AEGISStorageSystem(remote_name="gdrive", base_folder="AEGIS_Cluster_Artifacts")
        self.safety = SafetyGuard()
        self.dialogue = DialogueManager()
        self.nodes_config_path = nodes_config_path
        self.active_tasks: Dict[str, Dict[str, Any]] = {}

    def parse_user_request(self, raw_prompt: str) -> Dict[str, Any]:
        """Classifies voice/text request from the Tailscale portal in Hindi, Hinglish, or English."""
        parsed = self.dialogue.parse(raw_prompt)
        return parsed

    async def dispatch_task(self, prompt: str, target_node: str = "dgx-node-1", target_ip: str = "100.106.207.101", port: int = 8801) -> Dict[str, Any]:
        """Dispatches a task to a designated DGX node with dictated Google Drive upload commands."""
        manifest = self.storage.create_task_storage_manifest()
        task_id = manifest["task_id"]

        # Expected generated output
        expected_file = "generated_solution.py"
        upload_cmd = self.storage.generate_worker_upload_command(manifest, f"./workspace/{expected_file}")

        payload = {
            "task_id": task_id,
            "prompt": prompt,
            "expected_file": expected_file,
            "dictated_upload_cmd": upload_cmd,
            "callback_url": "http://100.106.207.27:9000/api/pi/task_complete"
        }

        self.active_tasks[task_id] = {
            "task_id": task_id,
            "prompt": prompt,
            "manifest": manifest,
            "primary_node": target_node,
            "status": "dispatched_to_primary",
            "created_at": datetime.utcnow().isoformat()
        }

        # Send over Tailscale mesh to target DGX
        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                res = await client.post(f"http://{target_ip}:{port}/api/execute", json=payload)
                if res.status_code == 200:
                    return {"status": "dispatched", "task_id": task_id, "manifest": manifest}
        except Exception:
            pass

        return {"status": "queued_locally", "task_id": task_id, "manifest": manifest, "payload": payload}

    async def handle_node_completion_and_handoff(self, task_id: str, primary_result: Dict[str, Any], reviewer_node_ip: str = "100.106.207.102", reviewer_port: int = 8802) -> Dict[str, Any]:
        """Receives completion from DGX 1, processes text on Pi, and dictates download command to DGX 2."""
        if task_id not in self.active_tasks:
            return {"error": "Unknown task ID"}

        task_info = self.active_tasks[task_id]
        manifest = task_info["manifest"]
        filename = primary_result.get("filename", "generated_solution.py")

        # Step 1: Text processing on Raspberry Pi
        text_summary = primary_result.get("text_summary", "Execution completed on DGX 1.")
        print(f"[Pi Hub] Processed primary result: {text_summary}")

        # Step 2: Generate download command for DGX 2
        dl_cmd = self.storage.generate_handoff_download_command(manifest, filename, stage="outputs", local_dest="./review_workspace")

        handoff_payload = {
            "task_id": task_id,
            "action": "code_review_and_qa",
            "dictated_download_cmd": dl_cmd,
            "target_file": f"./review_workspace/{filename}",
            "prompt": f"Review this code generated by DGX 1 for logic errors, write pytest suite, and execute tests."
        }

        # Step 3: Dispatch to DGX 2 (Reviewer) over Tailscale
        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                await client.post(f"http://{reviewer_node_ip}:{reviewer_port}/api/execute", json=handoff_payload)
                task_info["status"] = "in_review_on_dgx_2"
        except Exception:
            task_info["status"] = "handoff_ready"

        return {
            "status": "handoff_orchestrated",
            "task_id": task_id,
            "from_node": task_info["primary_node"],
            "to_node": "dgx-node-2",
            "dictated_download_cmd": dl_cmd,
            "pi_text_summary": text_summary
        }
